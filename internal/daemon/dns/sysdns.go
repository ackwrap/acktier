package dns

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
)

// ConfigureSystemSplitDNS registers 100.100.100.100 as the split-DNS resolver for magicSuffix on the host OS.
// Safe best-effort helper when running with OS TUN privileges.
func ConfigureSystemSplitDNS(ifName, magicSuffix string) error {
	sfx := strings.Trim(strings.TrimSpace(magicSuffix), ".")
	if sfx == "" {
		return nil
	}
	switch runtime.GOOS {
	case "windows":
		psCmd := fmt.Sprintf(
			`Get-DnsClientNrptRule | Where-Object { $_.Comment -eq 'AckTier-MagicDNS' } | Remove-DnsClientNrptRule -Force -ErrorAction SilentlyContinue; Add-DnsClientNrptRule -Namespace '.%s' -NameServers '%s' -Comment 'AckTier-MagicDNS'`,
			sfx, MagicDNSIPv4.String(),
		)
		return exec.Command("powershell", "-NoProfile", "-NonInteractive", "-Command", psCmd).Run()

	case "linux":
		if ifName == "" {
			return nil
		}
		_ = exec.Command("resolvectl", "dns", ifName, MagicDNSIPv4.String()).Run()
		return exec.Command("resolvectl", "domain", ifName, "~"+sfx).Run()

	case "darwin":
		if err := os.MkdirAll("/etc/resolver", 0o755); err != nil {
			return err
		}
		content := fmt.Sprintf("# Generated by AckTier\nnameserver %s\n", MagicDNSIPv4.String())
		return os.WriteFile(filepath.Join("/etc/resolver", sfx), []byte(content), 0o644)
	}
	return nil
}
